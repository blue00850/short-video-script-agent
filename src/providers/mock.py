class MockProvider(Provider):
    name = "mock"
    model = "mock-deterministic"

    def __init__(self, scenario: str = "normal"):
        self.scenario = scenario

    def generate(
        self,
        system: str,
        messages: List[Dict[str, str]],
        state: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        state = state or {}
        if state.get("phase") == "reviewer":
            decision = self._review(state)
        else:
            decision = self._writer(state)
        return {
            "text": json.dumps(decision, ensure_ascii=False),
            "usage": {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0},
            "model": self.model,
            "finish_reason": "stop",
        }

    # ------------------------------------------------------------------ writer
    def _writer(self, state: Dict[str, Any]) -> Dict[str, Any]:
        request = state.get("request", {})
        history = state.get("history", [])
        searches = [row for row in history if row.get("action") == "search_materials"]
        last = history[-1] if history else None
        scenario = self.scenario

        if not searches:
            query, product_id = self._initial_query(request, scenario)
            return self._decision(
                "search_materials",
                {"query": query, "product_id": product_id, "limit": 3},
                "先检索与主题相关的产品素材，确认可引用的事实。",
            )

        if scenario == "no_material":
            if len(searches) == 1:
                return self._decision(
                    "search_materials",
                    {
                        "query": "小影 AI 数字人 素材",
                        "product_id": request.get("product_id"),
                        "limit": 3,
                    },
                    "首次检索没有结果，改写查询并保留 product_id 再试一次。",
                )
            return self._decision(
                "ask_user",
                {
                    "question": "素材库中没有找到“AI 数字人直播”相关事实，是否补充产品素材，或更换主题？",
                    "kind": "insufficient_evidence",
                    "missing": ["product_material"],
                    "options": ["补充 P99 的产品资料", "改用已有素材的主题"],
                },
                "两次检索都没有素材，继续写会编造产品事实，向用户补充信息。",
            )

        if last and last.get("action") == "search_materials" and not last.get("ok"):
            return self._decision(
                "search_materials",
                {
                    "query": "小影 模板 竖屏",
                    "product_id": request.get("product_id"),
                    "limit": 3,
                },
                "检索工具超时，换一个更具体的查询重试一次。",
            )

        if not state.get("last_script"):
            return self._decision(
                "draft_script",
                self._draft_for(scenario, request, revision=False),
                "基于已检索到的素材写首稿，并保留素材 ID 与 claim ID。",
            )

        check = state.get("last_check")
        if check is None:
            return self._decision(
                "check_rules",
                {"script": state["last_script"]},
                "核对预计时长、镜头数、事实引用和品牌禁用表达。",
            )

        if not check.get("ok"):
            if scenario == "impossible" and state.get("draft_count", 0) >= 2:
                return self._finish_cannot_satisfy()
            if scenario == "impossible":
                return self._decision(
                    "draft_script",
                    self._draft_for(scenario, request, revision=True),
                    "检查显示 6.6 秒超过 6 秒目标；先压缩旁白再重检。",
                )
            if scenario in ("p01_30s", "rule_violation", "semantic_catch"):
                return self._decision(
                    "draft_script",
                    self._draft_for(scenario, request, revision=True),
                    self._revision_reason(check),
                )
            return self._finish_cannot_satisfy()

        review = state.get("last_review")
        if review and review.get("verdict") == "fail":
            return self._decision(
                "draft_script",
                self._draft_for(scenario, request, revision=True),
                "独立审核发现没有依据的能力延伸，删除后重新检查。",
            )
        if not state.get("reviewer_passed"):
            return self._decision(
                "review_facts",
                {},
                "机械检查通过，交给独立事实审核确认没有语义层编造。",
            )

        return self._decision(
            "finish",
            {
                "status": "completed",
                "message": "脚本已通过时长、品牌规则和独立事实审核，可以交付。",
                "risks": self._delivery_risks(scenario),
            },
            "时长、规则、事实审核均通过，交付最终脚本。",
        )

    # ------------------------------------------------------------------ review
    def _review(self, state: Dict[str, Any]) -> Dict[str, Any]:
        script = state.get("script") or {}
        findings = []
        for index, shot in enumerate(script.get("shots", []), start=1):
            narration = shot.get("narration", "")
            for phrase in ("不用手动打字", "不用自己打字", "自动识别"):
                if phrase in narration:
                    findings.append(
                        {
                            "severity": "error",
                            "shot": index,
                            "claim": narration,
                            "message": "素材只写了“支持字幕”，没有“%s”这类自动化能力，属于能力延伸。" % phrase,
                        }
                    )
        if findings:
            return {
                "verdict": "fail",
                "findings": findings,
                "summary": "发现 %d 处没有 claim 依据的能力延伸。" % len(findings),
            }
        return {"verdict": "pass", "findings": [], "summary": "所有产品事实都能在素材 claim 中找到依据。"}

    # ------------------------------------------------------------------ drafts
    def _initial_query(self, request: Dict[str, Any], scenario: str):
        product_id = request.get("product_id")
        if scenario == "no_material":
            return "AI 数字人直播", product_id
        if product_id == "P01" or scenario in ("p01_30s", "semantic_catch"):
            return "小影 字幕", product_id or "P01"
        if product_id == "P03" or scenario == "impossible":
            return "小影 模板", product_id or "P03"
        if product_id == "P02" or scenario in ("normal", "rule_violation", "step_limit"):
            return "小影 一键成片", product_id or "P02"
        return request.get("materials_query") or request.get("topic", ""), product_id

    def _draft_for(self, scenario: str, request: Dict[str, Any], revision: bool) -> Dict[str, Any]:
        if scenario in ("p01_30s", "semantic_catch"):
            if scenario == "semantic_catch":
                return P01_28 if revision else P01_SEMANTIC
            return P01_28 if revision else P01_38
        if scenario == "rule_violation":
            return NORMAL_P02 if revision else RULE_VIOLATION
        if scenario == "impossible":
            return IMPOSSIBLE_REV if revision else IMPOSSIBLE
        if scenario == "tool_failure":
            return P03_28
        return NORMAL_P02

    def _revision_reason(self, check: Dict[str, Any]) -> str:
        codes = [error.get("code") for error in check.get("errors", [])]
        if "duration_over" in codes:
            return "预计时长超过目标，压缩旁白并重检。"
        if "forbidden_phrase" in codes or "ungrounded_number" in codes:
            return "检查命中无依据的效率数字和禁用表达，删除后重检。"
        return "检查未通过，修改脚本后重检。"

    def _finish_cannot_satisfy(self) -> Dict[str, Any]:
        return self._decision(
            "finish",
            {
                "status": "cannot_satisfy",
                "message": "3 个镜头 × 每镜最短 2.0 秒 + 3 × 0.2 秒转场 = 6.6 秒，已经超过 6 秒目标；再压缩旁白也无法低于单镜最短时长。",
                "risks": [
                    "目标 6 秒低于 3 个镜头的最短总时长 6.6 秒，当前规则下无法满足。",
                    "未生成可交付脚本。",
                ],
            },
            "最短 3 个镜头也要 6.6 秒，无法压到 6 秒，明确说明不可满足。",
        )

    def _delivery_risks(self, scenario: str) -> List[str]:
        risks = ["素材为合成数据，发布前需替换为真实产品资料。"]
        if scenario in ("p01_30s", "semantic_catch"):
            risks.append("P01 仅包含“支持字幕”一条事实，未延伸识别准确率、自动翻译等能力。")
        if scenario == "rule_violation":
            risks.append("用户要求的“效率提升80%”无素材依据且命中品牌禁用表达，已删除。")
        return risks

    def _decision(self, action: str, args: Dict[str, Any], reason: str) -> Dict[str, Any]:
        return {"action": action, "args": args, "reason": reason}
